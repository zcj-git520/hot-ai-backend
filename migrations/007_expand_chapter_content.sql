## 提示词的作用

提示词直接影响模型的输出质量和准确性。

### 大模型如何理解提示词

大语言模型本质上是一个**概率预测器**：

1. 读取输入提示词
2. 理解语义和意图
3. 根据训练数据中的模式
4. 预测最可能的输出

### 影响输出的关键因素

#### 1. 明确性
```
❌ 模糊：帮我写点东西
✅ 明确：帮我写一篇关于 AI 教育的 800 字博客文章
```

#### 2. 上下文
```
❌ 缺少上下文：翻译这段文字
✅ 有上下文：作为法律文件，请将以下英文合同条款翻译为中文
```

#### 3. 约束条件
```
❌ 无约束：介绍 Python
✅ 有约束：用通俗易懂的语言，向零基础的文科生介绍 Python
```

#### 4. 示例引导
```
请按照以下格式分析：

示例：
输入：这家餐厅很棒
情感：正面

任务：
输入：这个产品质量太差了
情感：[模型填写]
```

### 常见的提示词模式

1. **直接指令模式**：请完成以下任务...
2. **对话模式**：我想讨论一个问题...
3. **问答模式**：请回答以下问题...
4. **模板模式**：请按照以下模板填写...

### 模型的限制与偏见

- **知识截止**：模型训练数据有截止时间
- **幻觉问题**：可能编造看似合理但不真实的信息
- **偏见问题**：训练数据中的偏见会被继承

### 本章要点总结

- 提示词通过影响模型的语义理解来控制输出
- 明确性、上下文、约束和示例是四大关键因素
- 掌握不同的提示词模式可以应对各种场景
- 了解模型的局限性有助于更好地使用

