## 什么是 Few-Shot

Few-Shot Learning 通过提供少量示例来引导模型输出。

### 基本原理

- **Zero-Shot**：直接提问，不给示例
- **One-Shot**：给一个示例
- **Few-Shot**：给多个示例（通常 2-5 个）

### 效果对比

**Zero-Shot**：
```
将以下句子翻译为正式语气：
输入：这个东西太棒了
```

**Few-Shot**：
```
请将以下句子改写为正式语气：

输入：这个东西太棒了
输出：该产品表现出色，令人印象深刻

输入：我觉得不行
输出：经过评估，该方案存在一定问题

输入：今天天气真好
输出：今日天气晴朗，适宜外出

输入：这个问题很简单
输出：该问题较为 straightforward
```

### Few-Shot 的设计技巧

#### 1. 示例选择
- 选择有代表性的示例
- 覆盖不同场景
- 避免偏差

#### 2. 示例格式
- 保持输入输出格式一致
- 清晰区分输入和输出
- 使用分隔符

#### 3. 示例数量
- 通常 2-5 个最佳
- 太多可能限制创造力
- 太少可能引导不够

### 实践练习

1. 设计一个情感分析的 Few-Shot 提示词
2. 创建一个文本分类的 Few-Shot 模板
3. 尝试不同数量的示例，比较效果

### 本章要点总结

- Few-Shot 通过示例引导模型理解任务
- 示例质量比数量更重要
- 保持格式一致性很关键
- 适用于需要固定输出的场景

