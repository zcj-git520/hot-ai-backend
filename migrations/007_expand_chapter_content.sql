## 思维链原理

思维链通过引导模型展示推理过程来提高准确性。

### 基本概念

让模型逐步展示思考过程，而不是直接给出答案。

### 效果对比

**普通提示**：
```
小明有 5 个苹果，给了小红 2 个，又买了 3 个，现在有几个？
答案：6
```

**思维链提示**：
```
小明有 5 个苹果，给了小红 2 个，又买了 3 个，现在有几个？

请逐步思考：
1. 初始：5 个苹果
2. 给小红 2 个：5 - 2 = 3 个
3. 又买 3 个：3 + 3 = 6 个
答案：6
```

### 使用场景

1. **数学问题**：逐步计算
2. **逻辑推理**：展示推理步骤
3. **复杂决策**：分析多个因素
4. **代码调试**：逐步排查问题

### 设计技巧

```
请按以下步骤分析问题：
1. 首先明确问题核心
2. 列出所有相关因素
3. 逐一分析每个因素
4. 给出综合结论
```

### 本章要点总结

- 思维链让模型展示推理过程
- 提高复杂问题的准确性
- 适用于数学、逻辑、决策等场景
- 关键是引导模型逐步思考

